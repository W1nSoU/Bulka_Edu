async def seed_materials():
    """Наповнює БД тестовими матеріалами."""
    print("🌱 Наповнення БД тестовими матеріалами...")
    
    # Ініціалізуємо БД
    await init_db()
    
    count = 0
    
    # 1. Загальні матеріали для всіх ролей
    for day, content in COMMON_MATERIALS.items():
        # Текстовий матеріал (для всіх)
        await add_or_update_material(
            role="ALL",
            day=day,
            content_type="text",
            title=content["title"],
            content=content["text"],
            resource_url=None,
            order_index=0
        )
        count += 1
        
        # Відео (для всіх)
        await add_or_update_material(
            role="ALL",
            day=day,
            content_type="video",
            title=f"Відео до Дня {day}",
            content=None,
            resource_url=content["video"],
            order_index=1
        )
        count += 1
    
    print(f"   ✅ Додано {count} загальних матеріалів")
    
    # 2. Специфічні матеріали для кожної ролі
    role_count = 0
    for role in AVAILABLE_ROLES:
        if role in ROLE_SPECIFIC:
            for day, text in ROLE_SPECIFIC[role].items():
                await add_or_update_material(
                    role=role,
                    day=day,
                    content_type="text",
                    title=f"Специфіка: {role}",
                    content=text,
                    resource_url=None,
                    order_index=10  # Після загальних
                )
                role_count += 1
    
    print(f"   ✅ Додано {role_count} специфічних матеріалів")
    
    print(f"\n🎉 Всього додано: {count + role_count} матеріалів")
    print("   Для 7 посад × 5 днів")


if __name__ == "__main__":
    asyncio.run(seed_materials())
